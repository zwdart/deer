#!/usr/bin/env python3
"""把 i18n/en.json + zh.json 转成 Dart 源码，嵌进 i18n.dart 依赖的 L10nData 类。

生成文件：lib/core/i18n_data.g.dart
用法：直接 import 'i18n_data.g.dart'; 用 L10nData.en / L10nData.zh 访问。
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
en = json.load(open(ROOT / 'assets' / 'i18n' / 'en.json', encoding='utf-8'))
zh = json.load(open(ROOT / 'assets' / 'i18n' / 'zh.json', encoding='utf-8'))

def _escape(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '')

def gen_map(d: dict, dart_name: str) -> str:
    lines = [f"  static const Map<String, String> {dart_name} = {{"]
    for k in sorted(d.keys()):
        lines.append(f'    "{_escape(k)}": "{_escape(d[k])}",')
    lines.append('  };')
    return '\n'.join(lines)

out = (
    "// AUTO-GENERATED BY _tool_gen_i18n_map.py — DO NOT EDIT BY HAND\n"
    "// 从 assets/i18n/*.json 生成，修改文案请改 JSON 再跑脚本。\n"
    "\n"
    "class L10nData {\n"
    + gen_map(en, 'en') + "\n\n"
    + gen_map(zh, 'zh') + "\n"
    "}\n"
)

out_path = ROOT / 'lib' / 'core' / 'i18n_data.g.dart'
out_path.write_text(out, encoding='utf-8')

print(f"✅ {len(en)} + {len(zh)} 条 → {out_path.relative_to(ROOT)}")
